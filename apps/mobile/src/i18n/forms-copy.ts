export function getFormsCopy(locale: Locale | string): FormsCopy {
  return locale === 'es' ? es : (en as unknown as FormsCopy);
}

export function useFormsCopy(): FormsCopy {
  const locale = useLanguageStore((state) => state.locale);
  return getFormsCopy(locale);
}
